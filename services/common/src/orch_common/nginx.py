"""Render the per-project nginx ``location`` blocks from manifests."""

import re
from collections.abc import Sequence

from orch_common.manifest import Manifest

# Same shape the manifest model enforces; re-checked here so nothing but safe
# tokens can ever reach the generated nginx syntax.
_SAFE_ID = re.compile(r"[a-z0-9][a-z0-9-]{0,39}")

HEADER = "# Generated by `orchctl render-nginx` - do not edit.\n"

_BLOCK = """\
location /p/{id}/ {{
    auth_request /_gate/{id};
    error_page 401 = @interstitial_{var};
    error_page 500 502 503 504 = @interstitial_{var};
    set $up_{var} http://{id}-entry:{port};
    proxy_pass $up_{var};
    proxy_set_header X-Forwarded-Prefix /p/{id};
    include /etc/nginx/snippets/project-proxy.conf;
}}
location = /_gate/{id} {{
    internal;
    set $gate_{var} http://control-plane:8000/internal/gate/{id};
    proxy_pass $gate_{var};
    proxy_set_header X-Real-IP $remote_addr;
    proxy_pass_request_body off;
    proxy_set_header Content-Length "";
    proxy_set_header Cookie $http_cookie;
}}
location @interstitial_{var} {{ return 302 /lab/p/{id}; }}
"""


def _render_one(m: Manifest) -> str:
    id_, port = m.id, m.entry.port
    if not isinstance(id_, str) or not _SAFE_ID.fullmatch(id_):
        raise ValueError(f"unsafe project id for nginx: {id_!r}")
    if type(port) is not int or not 1 <= port <= 65535:
        raise ValueError(f"unsafe port for nginx: {port!r}")
    return _BLOCK.format(id=id_, var=id_.replace("-", "_"), port=port)


def render_projects_conf(manifests: Sequence[Manifest]) -> str:
    """One routing block per manifest, in the given order."""
    return HEADER + "".join(_render_one(m) for m in manifests)
